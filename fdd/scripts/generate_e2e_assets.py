def generate_large_gl(rows: int = 10_000):
    """large-gl.xlsx — 대용량 GL (CI 환경 고려 10K행)."""
    wb = Workbook()
    ws = wb.active
    ws.title = "총계정원장"

    headers = [
        "전표번호",
        "전표일자",
        "계정코드",
        "계정명",
        "차변",
        "대변",
        "적요",
        "거래처",
    ]
    ws.append(headers)
    for cell in ws[1]:
        cell.font = Font(bold=True)

    account_pool = [
        ("1010", "현금및현금성자산"),
        ("1100", "매출채권"),
        ("1200", "재고자산"),
        ("2010", "유형자산"),
        ("3010", "매입채무"),
        ("3020", "미지급금"),
        ("5000", "매출액"),
        ("6010", "매출원가"),
        ("6020", "판매비와관리비"),
        ("7000", "영업외수익"),
    ]
    counterparties = ["고객사A", "고객사B", "공급사C", "공급사D", "내부", ""]

    for i in range(rows):
        acct_idx = i % len(account_pool)
        code, name = account_pool[acct_idx]
        month = (i % 12) + 1
        day = (i % 28) + 1
        debit = ((i + 1) * 10_000) % 100_000_000 if i % 2 == 0 else 0
        credit = 0 if i % 2 == 0 else ((i + 1) * 10_000) % 100_000_000
        cp = counterparties[i % len(counterparties)]

        ws.append(
            [
                f"LG-{i:06d}",
                f"2025-{month:02d}-{day:02d}",
                code,
                name,
                debit,
                credit,
                f"대량전표 {i}",
                cp,
            ]
        )

    out = ASSETS_DIR / "large-gl.xlsx"
    wb.save(str(out))
    size_mb = out.stat().st_size / 1024 / 1024
    print(f"  Created: {out} ({size_mb:.1f} MB, {rows:,} rows)")


def main():
    ASSETS_DIR.mkdir(parents=True, exist_ok=True)

    # .gitkeep 정리
    gitkeep = ASSETS_DIR / ".gitkeep"
    if gitkeep.exists():
        gitkeep.unlink()

    print("Generating E2E test assets...")
    generate_sample_tb()
    generate_sample_gl()
    generate_invalid_data()
    generate_large_gl()
    print("Done!")


if __name__ == "__main__":
    main()
