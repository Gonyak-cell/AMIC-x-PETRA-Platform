def _money_fmt(ws, col_letter: str, max_row: int):
    """금액 열에 천단위 구분 서식 적용."""
    for row in range(2, max_row + 1):
        cell = ws[f"{col_letter}{row}"]
        cell.number_format = "#,##0"


